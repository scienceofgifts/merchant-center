import React from 'react';
import { CheckCircle2, Sparkles, Wand2, Edit3, HelpCircle, AlertCircle } from 'lucide-react';
import { FieldProvenanceStatus } from '../types/feed';

interface FieldProvenanceBadgeProps {
  status?: FieldProvenanceStatus;
  label?: string;
  source?: string;
  className?: string;
}

export const FieldProvenanceBadge: React.FC<FieldProvenanceBadgeProps> = ({
  status = 'VERIFIED',
  label,
  source,
  className = '',
}) => {
  switch (status) {
    case 'GENERATED':
      return (
        <span
          className={`inline-flex items-center gap-1 px-1.5 py-0.5 rounded text-[10px] font-bold uppercase tracking-wider bg-purple-950/80 text-purple-300 border border-purple-800/80 shadow-xs ${className}`}
          title={source || 'Field generated by AI from product evidence and strategy rules'}
        >
          <Sparkles className="w-2.5 h-2.5 text-purple-400" />
          <span>{label || 'GENERATED'}</span>
        </span>
      );

    case 'OPTIMIZED':
      return (
        <span
          className={`inline-flex items-center gap-1 px-1.5 py-0.5 rounded text-[10px] font-bold uppercase tracking-wider bg-indigo-950/80 text-indigo-300 border border-indigo-800/80 shadow-xs ${className}`}
          title={source || 'Existing field enhanced by AI for Merchant Center compliance & gift intent'}
        >
          <Wand2 className="w-2.5 h-2.5 text-indigo-400" />
          <span>{label || 'OPTIMIZED'}</span>
        </span>
      );

    case 'VERIFIED':
      return (
        <span
          className={`inline-flex items-center gap-1 px-1.5 py-0.5 rounded text-[10px] font-bold uppercase tracking-wider bg-emerald-950/80 text-emerald-300 border border-emerald-800/80 shadow-xs ${className}`}
          title={source || 'Verified factual value extracted directly from source page/specs'}
        >
          <CheckCircle2 className="w-2.5 h-2.5 text-emerald-400" />
          <span>{label || 'VERIFIED'}</span>
        </span>
      );

    case 'USER_EDITED':
      return (
        <span
          className={`inline-flex items-center gap-1 px-1.5 py-0.5 rounded text-[10px] font-bold uppercase tracking-wider bg-amber-950/80 text-amber-300 border border-amber-800/80 shadow-xs ${className}`}
          title="Manually edited by feed manager"
        >
          <Edit3 className="w-2.5 h-2.5 text-amber-400" />
          <span>{label || 'USER EDITED'}</span>
        </span>
      );

    case 'UNVERIFIED':
      return (
        <span
          className={`inline-flex items-center gap-1 px-1.5 py-0.5 rounded text-[10px] font-bold uppercase tracking-wider bg-amber-950/60 text-amber-200 border border-amber-900/60 ${className}`}
          title="Mentioned in text but not definitively confirmed by technical/structured specifications"
        >
          <HelpCircle className="w-2.5 h-2.5 text-amber-400" />
          <span>{label || 'UNVERIFIED'}</span>
        </span>
      );

    case 'UNAVAILABLE':
    default:
      return (
        <span
          className={`inline-flex items-center gap-1 px-1.5 py-0.5 rounded text-[10px] font-bold uppercase tracking-wider bg-slate-900 text-slate-400 border border-slate-800 ${className}`}
          title="Not available from source. AI will not fabricate missing factual identifiers."
        >
          <AlertCircle className="w-2.5 h-2.5 text-slate-500" />
          <span>{label || 'UNAVAILABLE'}</span>
        </span>
      );
  }
};
